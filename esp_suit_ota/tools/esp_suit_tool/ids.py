"""Vendor and class identifiers, draft sections 8.4.8.1 to 8.4.8.3.

A vendor UUID is UUIDv5(DNS namespace, vendor domain), and its class UUID is UUIDv5(vendor UUID,
class name). A vendor may instead be a private enterprise number, sent as cbor-pen = #6.112(bstr);
its class UUID is UUIDv5(UUIDv5(NAMESPACE_CBOR_PEN, cbor-pen), class name).
"""
import hashlib
import uuid

from . import codes
from .cbor import Tag, dumps


def uuid5(namespace, name):
    """RFC 9562 version 5 over raw bytes (uuid.uuid5 takes only text before Python 3.12)."""
    name = name.encode() if isinstance(name, str) else bytes(name)
    h = bytearray(hashlib.sha1(namespace.bytes + name).digest()[:16])
    h[6] = (h[6] & 0x0f) | 0x50
    h[8] = (h[8] & 0x3f) | 0x80
    return uuid.UUID(bytes=bytes(h))


# section 8.4.8.1: UUIDv5(NAMESPACE_OID, the CBOR absolute OID 1.3.6.1.4.1)
NAMESPACE_CBOR_PEN = uuid5(uuid.NAMESPACE_OID, bytes.fromhex('d86f452b06010401'))


def vendor_uuid(domain):
    return uuid5(uuid.NAMESPACE_DNS, domain)


def class_uuid(vendor, name):
    return uuid5(vendor, name)


def pen_class_uuid(number, name):
    return uuid5(uuid5(NAMESPACE_CBOR_PEN, dumps(pen(number))), name)


def pen(number):
    """cbor-pen for an enterprise number: one RFC 9090 arc, base-128, high bit on all but the last byte."""
    if number < 0:
        raise ValueError('an enterprise number is not negative')
    out = bytearray([number & 0x7f])
    number >>= 7
    while number:
        out.insert(0, 0x80 | (number & 0x7f))
        number >>= 7
    return Tag(codes.PEN_TAG, bytes(out))


def c_header(vendor, klass, vendor_name, class_name):
    def arr(name, u):
        rows = [', '.join(f'0x{b:02x}' for b in u.bytes[i:i + 8]) for i in range(0, 16, 8)]
        return f'static const uint8_t {name}[16] = {{\n' + ''.join(f'    {r},\n' for r in rows) + '};\n'
    return (f'/* generated by esp-suit ids: vendor = UUIDv5(DNS, "{vendor_name}") = {vendor}, '
            f'class = UUIDv5(vendor, "{class_name}") = {klass} */\n'
            '#pragma once\n#include <stdint.h>\n\n' + arr('vendor_uuid', vendor) + '\n' + arr('class_uuid', klass))


def c_header_pen(number, klass, class_name):
    rows = [', '.join(f'0x{b:02x}' for b in klass.bytes[i:i + 8]) for i in range(0, 16, 8)]
    return (f'/* generated by esp-suit ids: vendor = enterprise number {number}, '
            f'class = UUIDv5(UUIDv5(NAMESPACE_CBOR_PEN, cbor-pen), "{class_name}") = {klass} */\n'
            '#pragma once\n#include <stdint.h>\n\n'
            f'static const uint32_t vendor_pen = {number};\n\n'
            'static const uint8_t class_uuid[16] = {\n' + ''.join(f'    {r},\n' for r in rows) + '};\n')
